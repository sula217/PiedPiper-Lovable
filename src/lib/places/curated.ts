/**
 * US PLACES (New York City, San Francisco, Chicago, Austin) are real
 * OpenStreetMap records retrieved on 2026-11-15 through a few Overpass API
 * queries and built by scripts/build-us-places.mjs. Names, street addresses,
 * coordinates and website links are exactly the OSM tags; nothing else is
 * stored. Public parks are "free to enter"; every other price is "not listed".
 * There are no curated US events: no reliable, permitted US event source is
 * configured, so concerts are suggested as venues, never as dated events.
 *
 * LEGACY (Kazakhstan) data from the earlier demo is kept below unchanged.
 * A small, manually verified dataset for Astana and Almaty.
 *
 * PLACES come from OpenStreetMap (retrieved 2026-11-14 through the Nominatim
 * search API, a handful of requests within its usage policy). Names,
 * coordinates, street addresses, website tags and cuisine are exactly as
 * recorded in OSM; `localName`/`localAddress` keep the original strings and
 * `address` is a transliteration of the same street. Website links are the
 * venues' own `website` tag in OSM. No ratings, prices, or opening hours are
 * stored, because OSM data for them was absent or unverified.
 *
 * EVENTS come from Ticketon.kz pages viewed manually on 2026-11-14. Ticketon
 * offers no public API we could find, so no scraping or private endpoints are
 * used: each event links to its official Ticketon page. Prices are the lowest
 * "from" price shown at verification; availability is NOT verified. Where a
 * page did not show the year, `yearShownOnSource` is false and the year was
 * taken from the current listing. Past events are filtered out at runtime.
 */
export const CURATED_VERIFIED_AT = "2026-11-14";
export const US_PLACES_VERIFIED_AT = "2026-11-15";
export const usPlaces: Place[] = usPlacesJson.map((p) => placeSchema.parse(p));
const OSM = (type: "node" | "way" | "relation", id: number) => ({
  name: "OpenStreetMap",
  url: `https://www.openstreetmap.org/${type}/${id}`,
  attribution: "© OpenStreetMap contributors (ODbL)",
  kind: "curated" as const,
});
const osmMap = (type: "node" | "way" | "relation", id: number) =>
  `https://www.openstreetmap.org/${type}/${id}`;
const TICKETON = (url: string) => ({
  name: "Ticketon (manually verified)",
  url,
  attribution: null,
  kind: "curated" as const,
});
const base = { country: "Kazakhstan", lastVerified: CURATED_VERIFIED_AT };

type PlaceSeed = Omit<
  Place,
  "type" | "country" | "lastVerified" | "source" | "mapUrl"
> & { osm: ["node" | "way" | "relation", number] };
const place = (p: PlaceSeed): Place => {
  const { osm, ...rest } = p;
  return {
    ...rest,
    ...base,
    type: "place",
    mapUrl: osmMap(osm[0], osm[1]),
    source: OSM(osm[0], osm[1]),
  };
};

